from reportlab.platypus import SimpleDocTemplate, Paragraph
from reportlab.lib.styles import getSampleStyleSheet
from datetime import datetime

def generate_pdf(
    industry,
    country,
    region,
    funding_round,
    funding_amount,
    employee_count,
    revenue,
    valuation,
    score,
    risk,
    ml_prediction,
    dss_recommendation,
):

    filename = "InvestWise_AI_Report.pdf"

    doc = SimpleDocTemplate(filename)

    styles = getSampleStyleSheet()

    elements = []

    title = Paragraph("<b><font size=20>InvestWise AI Report</font></b>", styles["Title"])
    elements.append(title)

    elements.append(Paragraph("<br/>", styles["Normal"]))

    elements.append(Paragraph(f"<b>Date:</b> {datetime.now().strftime('%d-%m-%Y %H:%M')}", styles["Normal"]))

    elements.append(Paragraph("<br/>", styles["Normal"]))

    elements.append(Paragraph("<b>Startup Details</b>", styles["Heading2"]))

    elements.append(Paragraph(f"Industry : {industry}", styles["Normal"]))
    elements.append(Paragraph(f"Country : {country}", styles["Normal"]))
    elements.append(Paragraph(f"Region : {region}", styles["Normal"]))
    elements.append(Paragraph(f"Funding Round : {funding_round}", styles["Normal"]))
    elements.append(Paragraph(f"Funding Amount : ${funding_amount:,.2f}", styles["Normal"]))
    elements.append(Paragraph(f"Employee Count : {employee_count}", styles["Normal"]))
    elements.append(Paragraph(f"Estimated Revenue : ${revenue:,.2f}", styles["Normal"]))
    elements.append(Paragraph(f"Estimated Valuation : ${valuation:,.2f}", styles["Normal"]))

    elements.append(Paragraph("<br/>", styles["Normal"]))

    elements.append(Paragraph("<b>AI Analysis</b>", styles["Heading2"]))

    elements.append(Paragraph(f"Investment Score : {score}/100", styles["Normal"]))
    elements.append(Paragraph(f"Risk Level : {risk}", styles["Normal"]))
    elements.append(Paragraph(f"Decision Tree Prediction : {ml_prediction}", styles["Normal"]))
    elements.append(Paragraph(f"DSS Recommendation : {dss_recommendation}", styles["Normal"]))

    elements.append(Paragraph("<br/>", styles["Normal"]))

    elements.append(Paragraph("<b>Final Recommendation</b>", styles["Heading2"]))

    if dss_recommendation == "Invest":
        final = "INVEST"
    elif dss_recommendation == "Invest with Caution":
        final = "INVEST WITH CAUTION"
    else:
        final = "DO NOT INVEST"

    elements.append(Paragraph(f"<b>{final}</b>", styles["Normal"]))

    elements.append(Paragraph("<br/>", styles["Normal"]))

    elements.append(Paragraph(
        "This report has been automatically generated by InvestWise AI using Decision Tree Machine Learning and Decision Support System (DSS).",
        styles["Italic"]
    ))

    doc.build(elements)

    return filename